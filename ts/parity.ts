import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ts = import.meta.dir;
const src = join(ts, "..", "src");
const testFiles = [
  ...readdirSync(join(ts, "packages")).flatMap((p) => {
    try {
      return readdirSync(join(ts, "packages", p, "test")).map((f) => join(ts, "packages", p, "test", f));
    } catch {
      return [];
    }
  }),
  ...readdirSync(join(ts, "test")).map((f) => join(ts, "test", f)),
].filter((f) => f.endsWith(".ts"));
const ported = testFiles.map((f) => readFileSync(f, "utf8")).join("\n");
/** Rust tests that don't apply to the TypeScript app, `module::test` → why (`parity-na.json`). */
const notApplicable = JSON.parse(readFileSync(join(ts, "parity-na.json"), "utf8")) as Record<string, string>;

interface Row {
  module: string;
  names: string[];
  missing: string[];
}

const rows: Row[] = [];
for (const f of readdirSync(src).filter((x) => x.endsWith(".rs")).sort()) {
  const text = readFileSync(join(src, f), "utf8");
  const module = f.slice(0, -3);
  const names = [...text.matchAll(/#\[test\]\s*(?:#\[[^\]]*\]\s*)*fn\s+([a-z0-9_]+)/g)].map((m) => m[1] ?? "").filter((n) => !(`${module}::${n}` in notApplicable));
  if (names.length === 0) continue;
  const missing = names.filter((n) => !new RegExp(`["'\`]${n}\\b`).test(ported));
  rows.push({ module, names, missing });
}
const total = rows.reduce((n, r) => n + r.names.length, 0);
const done = rows.reduce((n, r) => n + r.names.length - r.missing.length, 0);
const lines = [
  "# Rust tests ported",
  "",
  `Generated by \`bun parity.ts\`: ${done} of ${total} Rust tests have a bun test of the same name.`,
  "A test ported under another name shows as a gap: rename it after the Rust test. Tests that don't apply are",
  "left out of the count and listed at the end with the reason (`parity-na.json`).",
  "",
  "| Module | Ported | Not yet |",
  "| --- | --- | --- |",
  ...rows.map((r) => `| ${r.module} | ${r.names.length - r.missing.length}/${r.names.length} | ${r.missing.join(", ")} |`),
  "",
  "## Not applicable",
  "",
  "| Rust test | Why |",
  "| --- | --- |",
  ...Object.entries(notApplicable).map(([k, why]) => `| ${k} | ${why} |`),
  "",
];
writeFileSync(join(ts, "PARITY.md"), lines.join("\n"));
console.log(`${done} of ${total}`);
